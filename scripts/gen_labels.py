"""Generate the labels of the panel from the translations of the dialogs.

The panel shows the same names and help texts as the dialogs. Run this script
after changing ``translations/*.json``; a test checks that the file is current.

    python scripts/gen_labels.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
COMPONENT = ROOT / "custom_components" / "shutter_assistant"
TRANSLATIONS = COMPONENT / "translations"
TARGET = COMPONENT / "frontend" / "labels.js"
LANGUAGES = ("de", "en")
HEADER = "// Generated by scripts/gen_labels.py from the translations, do not edit by hand.\n"


def _steps(data: dict[str, Any]) -> list[dict[str, Any]]:
    """All steps and sections of the dialogs that contain fields."""
    found: list[dict[str, Any]] = []
    roots = [data.get("config", {}), data.get("options", {})]
    roots += list(data.get("config_subentries", {}).values())
    for root in roots:
        for step in root.get("step", {}).values():
            found.append(step)
            found.extend(step.get("sections", {}).values())
    return found


def labels(data: dict[str, Any]) -> dict[str, list[str]]:
    """Field key -> [name, help]. The same key has the same text everywhere."""
    result: dict[str, list[str]] = {}
    for step in _steps(data):
        names = step.get("data", {})
        helps = step.get("data_description", {})
        for key, name in names.items():
            help_text = helps.get(key, "")
            if key not in result:
                result[key] = [name, help_text]
                continue
            known = result[key]
            if known[0] != name or (help_text and known[1] and known[1] != help_text):
                raise ValueError(f"Field {key} has different texts: {known} / {[name, help_text]}")
            if help_text and not known[1]:
                known[1] = help_text
    return dict(sorted(result.items()))


def build() -> str:
    out: dict[str, dict[str, Any]] = {
        "LABELS": {},
        "CHOICES": {},
        "ERRORS": {},
        "STATUS": {},
        "NEXT_ACTION": {},
    }
    for language in LANGUAGES:
        data = json.loads((TRANSLATIONS / f"{language}.json").read_text(encoding="utf-8"))
        out["LABELS"][language] = labels(data)
        out["CHOICES"][language] = {
            key: value["options"] for key, value in sorted(data.get("selector", {}).items())
        }
        out["ERRORS"][language] = data["config"]["error"]
        out["STATUS"][language] = data["entity"]["sensor"]["status"]["state"]
        next_action = data["entity"]["sensor"]["next_action"]["state_attributes"]["action"]
        out["NEXT_ACTION"][language] = next_action["state"]
    parts = [HEADER]
    for name, value in out.items():
        parts.append(f"export const {name} = {json.dumps(value, ensure_ascii=False, indent=1)};\n")
    return "".join(parts)


def main() -> int:
    content = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(f"{TARGET.relative_to(ROOT)} is outdated, run scripts/gen_labels.py")
            return 1
        return 0
    TARGET.write_text(content, encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
